/**
 * การคำนวณ "ต่อหัวนิสิต" — ส่วนที่ตกลงแล้วและไม่ขึ้นกับการตัดสินใจ A–D
 *
 * เหตุผลที่แยกเป็นไฟล์เดียว: prototype เดิมเขียน `Q > 0 ? TVC / Q : 0` ซ้ำ 4 ที่
 * ซึ่งคืน `0` เมื่อไม่มีนิสิต ทำให้ CM = 0 แล้ว Q* กลายเป็น null "เงียบๆ"
 * โดยไม่บอกสาเหตุ (ดู SA.md หัวข้อ 16.3 ข้อ 4) — ที่นี่คืน `null` เพื่อบังคับให้
 * ผู้เรียกจัดการกรณีไม่มีนิสิตอย่างชัดเจน
 */

/**
 * หารยอดรวมด้วยจำนวนนิสิต
 *
 * @returns ค่าต่อหัว หรือ `null` เมื่อ `q <= 0` หรือ `q` ไม่ใช่จำนวนที่ใช้ได้
 */
export function perHead(total: number, q: number): number | null {
  if (!Number.isFinite(total) || !Number.isFinite(q) || q <= 0) return null;
  return total / q;
}
