const sum = (xs: number[]) => Math.round(xs.reduce((a, b) => a + b, 0) * 100) / 100;

describe('ค่าเสื่อมราคา 2567–2568 (ถอดจาก PDF)', () => {
  it('ครบทุกหน่วยงาน', () => {
    expect(DEP_UNITS.map((u) => u.name).sort()).toEqual(Object.keys(PRINTED).sort());
  });

  it.each(DEP_UNITS)('ยอดรวม $name ตรงกับไฟล์', (u) => {
    const [p67, p68] = PRINTED[u.name]!;
    if (p67 === null) expect(u.y2567).toBeNull();
    else expect(depTotals(u.y2567)!.total).toBeCloseTo(p67, 1);
    expect(depTotals(u.y2568)!.total).toBeCloseTo(p68, 1);
  });

  it.each([2567, 2568] as const)('ยอดรวมแยกแหล่งเงินปี %i ตรงกับไฟล์', (y) => {
    const rows = DEP_UNITS.map((u) => depTotals(y === 2567 ? u.y2567 : u.y2568)).filter(
      (t) => t !== null,
    );
    expect(sum(rows.map((t) => t.budget))).toBeCloseTo(DEP_PDF_TOTALS[y].budget, 1);
    expect(sum(rows.map((t) => t.revenue))).toBeCloseTo(DEP_PDF_TOTALS[y].revenue, 1);
    expect(sum(rows.map((t) => t.total))).toBeCloseTo(DEP_PDF_TOTALS[y].total, 1);
  });

  it('dep ของคณะในระบบคำนวณ (Google Sheet) = ยอดปี 2567', () => {
    for (const f of RAW.FACS) {
      const u = DEP_UNITS.find((d) => d.name === f.name);
      expect(u, f.name).toBeDefined();
      expect(Math.abs(depTotals(u!.y2567)!.total - f.dep), f.name).toBeLessThan(0.05);
    }
  });
});
